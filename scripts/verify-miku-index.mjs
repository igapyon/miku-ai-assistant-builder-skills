#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(fs.readFileSync(path.resolve(repoRoot, "package.json"), "utf8"));
const configuration = packageJson.mikuIndex;

assert.ok(configuration?.path, "package.json must declare mikuIndex.path");
assert.equal(configuration.required, true, "mikuIndex must be required");

const indexPath = path.resolve(repoRoot, configuration.path);
assert.equal(fs.existsSync(indexPath), true, `required miku-indexgen index is missing: ${configuration.path}`);

const skillRoot = path.dirname(indexPath);
const index = JSON.parse(fs.readFileSync(indexPath, "utf8"));
assert.equal(index.generator, "miku-indexgen", "index.json must be generated by miku-indexgen");
assert.equal(index.generation?.schemaVersion, 1, "missing miku-indexgen generation metadata");
assert.ok(Array.isArray(index.files), "miku-indexgen index must contain files");

const includeExtensions = new Set(index.generation.includeExtensions ?? []);
const actual = new Map();
walk(skillRoot);
const indexed = new Map(index.files.map((entry) => [entry.path, entry]));

assert.deepEqual(new Set(indexed.keys()), new Set(actual.keys()), "miku-indexgen index file set is stale");
for (const [relativePath, stat] of actual) {
  assert.equal(indexed.get(relativePath).size, stat.size, `stale indexed size: ${relativePath}`);
}
process.stdout.write("miku-indexgen index is current\n");

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((left, right) => compareUtf16(left.name, right.name))) {
    if (entry.name === ".DS_Store" || entry.name === "index.json") continue;
    const absolutePath = path.resolve(dir, entry.name);
    if (entry.isDirectory()) {
      walk(absolutePath);
      continue;
    }
    const extension = path.extname(entry.name).slice(1);
    if (!includeExtensions.has(extension)) continue;
    actual.set(path.relative(skillRoot, absolutePath).split(path.sep).join("/"), fs.statSync(absolutePath));
  }
}

function compareUtf16(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}
